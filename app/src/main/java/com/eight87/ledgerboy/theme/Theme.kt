@file:OptIn(androidx.compose.material3.ExperimentalMaterial3ExpressiveApi::class)

package com.eight87.ledgerboy.theme

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.ColorScheme
import androidx.compose.material3.MaterialExpressiveTheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.expressiveLightColorScheme
import androidx.compose.runtime.Composable

/**
 * ledgerboy app theme — Material 3 Expressive, dark-first.
 *
 * m3-expressive.md decisions baked in:
 *  - gotcha 1: material3 pinned to 1.5.0-alpha18 so
 *    `MaterialExpressiveTheme` / `expressiveLightColorScheme` are public;
 *    `expressiveDarkColorScheme()` does not exist yet, so dark mode pairs
 *    `darkColorScheme(...)` with the brand seeds. Both produce the full
 *    surface-tier ladder.
 *  - pattern 1/2: `MaterialExpressiveTheme` is the root (not
 *    `MaterialTheme`); the surface-tier ladder does the lift, elevation
 *    stays flat.
 *
 * No dynamic colour (Material You wallpaper extraction is explicitly off
 * — hand-picked accents per m3-expressive.md). No album-art tint layer
 * (that was a tonearmboy concern). Light mode is generated by the
 * expressive factory but ledgerboy ships dark-first; light gets a polish
 * pass once the dark surface looks right.
 */
private val DarkColorScheme: ColorScheme =
  darkColorScheme(primary = Teal80, secondary = TealGrey80, tertiary = Gold80)

private val LightColorScheme: ColorScheme = expressiveLightColorScheme()

@Composable
fun LedgerboyTheme(
  darkTheme: Boolean = isSystemInDarkTheme(),
  content: @Composable () -> Unit,
) {
  val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme
  MaterialExpressiveTheme(
    colorScheme = colorScheme,
    typography = Typography,
    content = content,
  )
}
